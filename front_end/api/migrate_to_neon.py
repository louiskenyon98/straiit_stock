def arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create Neon catalogue/portal schemas and import both SQLite databases."
    )
    parser.add_argument(
        "--catalogue-db", type=Path, default=DEFAULT_CATALOGUE_DB,
        help=f"source catalogue SQLite database (default: {DEFAULT_CATALOGUE_DB})",
    )
    parser.add_argument(
        "--portal-db", type=Path, default=DEFAULT_PORTAL_DB,
        help=f"source portal SQLite database (default: {DEFAULT_PORTAL_DB})",
    )
    parser.add_argument(
        "--replace", action="store_true",
        help="drop and recreate only the catalogue and portal schemas before importing",
    )
    parser.add_argument(
        "--check-only", action="store_true",
        help="validate the SQLite sources and show row counts without connecting to Neon",
    )
    return parser.parse_args()


def open_sqlite(path: Path) -> sqlite3.Connection:
    resolved = path.expanduser().resolve()
    if not resolved.is_file():
        raise SystemExit(f"SQLite database not found: {resolved}")
    connection = sqlite3.connect(f"file:{resolved.as_posix()}?mode=ro", uri=True)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA query_only = ON")
    return connection


def table_columns(connection: sqlite3.Connection, table: str) -> list[str]:
    return [str(row[1]) for row in connection.execute(f'PRAGMA table_info("{table}")')]


def source_counts(
    connection: sqlite3.Connection, tables: Iterable[str], source_name: str
) -> dict[str, int]:
    available = {
        str(row[0])
        for row in connection.execute("SELECT name FROM sqlite_master WHERE type='table'")
    }
    missing = [table for table in tables if table not in available]
    if missing:
        raise SystemExit(f"{source_name} is missing required tables: {', '.join(missing)}")
    return {
        table: int(connection.execute(f'SELECT COUNT(*) FROM "{table}"').fetchone()[0])
        for table in tables
    }


def print_counts(label: str, counts: dict[str, int]) -> None:
    print(label)
    for table, count in counts.items():
        print(f"  {table}: {count:,}")


def postgres_driver():
    try:
        import psycopg
        from psycopg import sql
    except ImportError as error:
        raise SystemExit(
            'PostgreSQL driver missing. Run: python -m pip install "psycopg[binary]>=3.2,<4"'
        ) from error
    return psycopg, sql


def direct_database_url() -> str:
    value = os.environ.get("NEON_DIRECT_DATABASE_URL", "").strip()
    if not value:
        raise SystemExit(
            "NEON_DIRECT_DATABASE_URL is not set. Copy the direct connection string "
            "from Neon and set it in this terminal."
        )
    parsed = urlparse(value)
    if parsed.scheme not in {"postgres", "postgresql"} or not parsed.hostname:
        raise SystemExit("NEON_DIRECT_DATABASE_URL is not a valid PostgreSQL connection string.")
    if "-pooler" in parsed.hostname:
        raise SystemExit(
            "Use Neon's direct connection string for migrations, not the pooled hostname."
        )
    return value


def convert_value(schema: str, table: str, column: str, value: Any) -> Any:
    if (schema, table, column) in BOOLEAN_COLUMNS and value is not None:
        return bool(value)
    if table == "quotes" and column == "valid_until" and value == "":
        return None
    return value


def copy_table(
    sqlite_connection: sqlite3.Connection,
    postgres_cursor: Any,
    sql: Any,
    schema: str,
    table: str,
    batch_size: int = 1_000,
) -> int:
    columns = table_columns(sqlite_connection, table)
    if not columns:
        raise RuntimeError(f"No columns found for {schema}.{table}")
    copy_statement = sql.SQL("COPY {}.{} ({}) FROM STDIN").format(
        sql.Identifier(schema),
        sql.Identifier(table),
        sql.SQL(", ").join(sql.Identifier(column) for column in columns),
    )
    source_cursor = sqlite_connection.execute(f'SELECT * FROM "{table}" ORDER BY id')
    copied = 0
    with postgres_cursor.copy(copy_statement) as destination:
        while rows := source_cursor.fetchmany(batch_size):
            for row in rows:
                destination.write_row(
                    tuple(
                        convert_value(schema, table, column, row[column])
                        for column in columns
                    )
                )
                copied += 1
    return copied


def reset_identity(postgres_cursor: Any, schema: str, table: str) -> None:
    relation = f'{schema}."{table}"'
    postgres_cursor.execute("SELECT pg_get_serial_sequence(%s, 'id')", (relation,))
    sequence = postgres_cursor.fetchone()[0]
    if not sequence:
        return
    postgres_cursor.execute(f'SELECT COALESCE(MAX(id), 0) FROM "{schema}"."{table}"')
    maximum = int(postgres_cursor.fetchone()[0])
    postgres_cursor.execute(
        "SELECT setval(%s::regclass, %s, %s)",
        (sequence, maximum if maximum else 1, bool(maximum)),
    )


def target_count(postgres_cursor: Any, schema: str, table: str) -> int:
    postgres_cursor.execute(f'SELECT COUNT(*) FROM "{schema}"."{table}"')
    return int(postgres_cursor.fetchone()[0])


def ensure_empty_targets(postgres_cursor: Any) -> None:
    populated: list[str] = []
    for schema, tables in (("catalogue", CATALOGUE_TABLES), ("portal", PORTAL_TABLES)):
        for table in tables:
            count = target_count(postgres_cursor, schema, table)
            if count:
                populated.append(f"{schema}.{table} ({count:,} rows)")
    if populated:
        details = "\n  ".join(populated)
        raise RuntimeError(
            "Neon already contains Straiit data. Nothing was changed. "
            "Use --replace only if you intend to discard it:\n  " + details
        )


def prepare_target(postgres_cursor: Any, replace: bool) -> None:
    if replace:
        print("Replacing the Neon catalogue and portal schemas...")
        postgres_cursor.execute("DROP SCHEMA IF EXISTS catalogue CASCADE")
        postgres_cursor.execute("DROP SCHEMA IF EXISTS portal CASCADE")
    postgres_cursor.execute(POSTGRES_SCHEMA)
    if not replace:
        ensure_empty_targets(postgres_cursor)


def migrate(args: argparse.Namespace) -> None:
    catalogue = open_sqlite(args.catalogue_db)
    portal = open_sqlite(args.portal_db)
    try:
        catalogue_counts = source_counts(catalogue, CATALOGUE_TABLES, "Catalogue database")
        portal_counts = source_counts(portal, PORTAL_TABLES, "Portal database")
        print_counts("Catalogue source:", catalogue_counts)
        print_counts("Portal source:", portal_counts)
        if args.check_only:
            print("Source validation complete; Neon was not changed.")
            return

        psycopg, sql = postgres_driver()
        url = direct_database_url()
        print("Connecting to Neon with the direct connection...")
        with psycopg.connect(url) as postgres:
            with postgres.cursor() as cursor:
                prepare_target(cursor, args.replace)
                for schema, source, tables, expected in (
                    ("catalogue", catalogue, CATALOGUE_TABLES, catalogue_counts),
                    ("portal", portal, PORTAL_TABLES, portal_counts),
                ):
                    print(f"Importing {schema}...")
                    for table in tables:
                        copied = copy_table(source, cursor, sql, schema, table)
                        if copied != expected[table]:
                            raise RuntimeError(
                                f"Copy count mismatch for {schema}.{table}: "
                                f"expected {expected[table]}, copied {copied}"
                            )
                        reset_identity(cursor, schema, table)
                        print(f"  {table}: {copied:,}")

                for schema, tables, expected in (
                    ("catalogue", CATALOGUE_TABLES, catalogue_counts),
                    ("portal", PORTAL_TABLES, portal_counts),
                ):
                    for table in tables:
                        actual = target_count(cursor, schema, table)
                        if actual != expected[table]:
                            raise RuntimeError(
                                f"Verification failed for {schema}.{table}: "
                                f"expected {expected[table]}, found {actual}"
                            )
            postgres.commit()
        print("Migration complete. Both Neon schemas were committed successfully.")
    finally:
        catalogue.close()
        portal.close()


def main() -> int:
    args = arguments()
    try:
        migrate(args)
    except (RuntimeError, sqlite3.Error) as error:
        print(f"Migration failed: {error}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("Migration cancelled; the Neon transaction was rolled back.", file=sys.stderr)
        return 130
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
