#!/usr/bin/env python3
"""Create the Neon schemas and copy both Straiit SQLite databases into them.

The migration is intentionally separate from the runtime API. It performs one
transaction against a direct (non-pooled) Neon connection and rolls everything
back if schema creation, copying, or row-count verification fails.
"""

from __future__ import annotations

import argparse
import os
import sqlite3
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import Any
from urllib.parse import urlparse


PROJECT_ROOT = Path(__file__).resolve().parents[1]
